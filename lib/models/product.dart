class Product {
  final String id;
  final String title;
  final double price;
  final String imageUrl;
  final double rating;
  final int reviewsCount;
  final String description;

  Product({
    required this.id,
    required this.title,
    required this.price,
    required this.imageUrl,
    required this.rating,
    required this.reviewsCount,
    required this.description,
  });
}